text3 = 'В саду кот нашёл мышь, и лиса это увидела.'

index1 = {}

def normalize(text, lemmatize=True):
    text = text.lower()
    text = re.sub(r'[^а-яёa-z0-9\s]', ' ', text)
    words = [w for w in text.split() if w not in stop]
    if lemmatize:
        words = [lem.get(w, w) for w in words]
    return words


def add_doc(doc_id, text, ind, used_ids, lemmatize=True):
    if doc_id in used_ids:
        raise ValueError(f'Документ с ID={doc_id} уже существует.')
    words = normalize(text, lemmatize=lemmatize)
    for w in set(words):
        ind.setdefault(w, set()).add(doc_id)
    used_ids.add(doc_id)


def print_index(index):
    print('\nindex = {')
    for k in sorted(index):
        print(f'  "{k}": {sorted(index[k])},')
    print('}')


used_ids = set()
add_doc(1, text1, index1, used_ids)
add_doc(2, text2, index1, used_ids)
add_doc(3, text3, index1, used_ids)
print_index(index1)

while True:
    raw = input('Введите ID документа (n — завершить): ').strip()
    if raw.lower() == 'n':
        break
    try:
        doc_id = int(raw)
    except ValueError:
        print('ID должен быть целым числом.')
        continue
    if doc_id in used_ids:
        print('Такой ID уже используется. Введите другой.')
        continue
    text = input(f'Введите текст документа ID={doc_id}: ')
    # По ТЗ для новых документов выполняем нормализацию без лемматизации.
    add_doc(doc_id, text, index1, used_ids, lemmatize=False)
    print(f'Документ ID={doc_id} добавлен.')
    print_index(index1)
