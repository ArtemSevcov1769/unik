import re

text1 = 'Солнце светит ярко, и птицы поют в лесу.'
text2 = 'В лесу растут деревья, а птицы строят гнёзда.'
text3 = 'В саду кот нашёл мышь, и лиса это увидела.'

stop = ['и', 'в', 'во', 'на', 'а', 'но', 'с', 'со', 'к', 'по', 'за',
        'из', 'у', 'о', 'об', 'от', 'до', 'для', 'же', 'бы', 'ли', 'это']

lem = {
    'быстрая': 'быстрый', 'прыгает': 'прыгать', 'ленивую': 'ленивый',
    'поют': 'петь', 'светит': 'светить', 'птицы': 'птица',
    'лесу': 'лес', 'деревья': 'дерево', 'строят': 'строить',
    'гнёзда': 'гнездо', 'растут': 'расти', 'нашёл': 'найти',
    'увидела': 'увидеть', 'саду': 'сад', 'собаку': 'собака'
}

def normalize(text):
    text = text.lower()
    text = re.sub(r'[^а-яёa-z0-9\s]', ' ', text)
    words = text.split()
    words = [w for w in words if w not in stop]
    words = [lem.get(w, w) for w in words]
    return words

print(normalize(text1))
print(normalize(text2))
print(normalize(text3))